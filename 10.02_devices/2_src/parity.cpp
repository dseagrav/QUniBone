int get_even_parity_8b(uint8_t val){
    return(EVEN_PARITY_8B[val]);
}

int get_even_parity_16b(uint16_t val){
    uint8_t tmp[2];
    tmp[0] = ((val&0xFF00)>>8);
    tmp[1] = (val&0x00FF);
    return(EVEN_PARITY_8B[tmp[0]^tmp[1]]);
}

int get_odd_parity_8b(uint8_t val){
    return(ODD_PARITY_8B[val]);
}

int get_odd_parity_16b(uint16_t val){
    uint8_t tmp[2];
    tmp[0] = ((val&0xFF00)>>8);
    tmp[1] = (val&0x00FF);
    return(ODD_PARITY_8B[tmp[0]^tmp[1]]);
}
